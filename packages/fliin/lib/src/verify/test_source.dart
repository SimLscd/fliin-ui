import 'package:fliin_schema/fliin_schema.dart';

/// Un littéral Dart pour [text], quel que soit son contenu : une apostrophe
/// ou un `$` dans `--out` ou `--import` ne casse pas la compilation.
String _dartString(String text) {
  final escaped = text
      .replaceAll(r'\', r'\\')
      .replaceAll("'", r"\'")
      .replaceAll(r'$', r'\$')
      .replaceAll('\n', r'\n')
      .replaceAll('\r', r'\r');
  return "'$escaped'";
}

/// Le test que `fliin verify` écrit dans `test/.fliin/` : les imports de
/// l'élément, puis l'entrée pompée sous `{prefix}Scope` par le harnais. Le
/// `Builder` donne à l'entrée un contexte sous le scope, pour que
/// `{prefix}Scope.of(context)` y résolve. L'entrée est du Dart par
/// construction ; les chemins et les URI sont échappés. [canvas] et
/// [settleMs] viennent du manifeste ; [goldens] est le dossier local des
/// références téléchargées. Les exceptions de contraste du thème du projet
/// (ADR 0014) passent au harnais, qui en fait des avertissements.
String verifyTestSource({
  required String item,
  required String version,
  required String prefix,
  required String entry,
  required Set<String> imports,
  required String outDir,
  required List<String> variants,
  VerifyCanvas? canvas,
  int? settleMs,
  String? goldens,
}) {
  final sortedImports = imports.toList()..sort();
  return '''
// Generated by fliin verify. Rerun the command instead of editing.
import 'package:flutter/widgets.dart';
${[for (final uri in sortedImports) 'import ${_dartString(uri)};'].join('\n')}

import 'fliin_harness.dart';

void main() {
  fliinVerify(
    item: '$item',
    version: '$version',
    outDir: ${_dartString(outDir)},
${goldens == null ? '' : '    goldens: ${_dartString(goldens)},\n'}${_canvasArguments(canvas)}${settleMs == null ? '' : '    settle: const Duration(milliseconds: $settleMs),\n'}${variants.isEmpty ? '' : "    variants: [\n      for (final variant in fliinMatrix)\n        if (const {${[for (final id in variants) "'$id'"].join(', ')}}.contains(variant.id)) variant,\n    ],\n"}    contrastExceptions: [
      for (final e in ${prefix}Tokens.defaults.contrastExceptions)
        if (e.brightness == Brightness.light ? ${prefix}Tokens.defaults.light : ${prefix}Tokens.defaults.dark
            case final colors)
          (
            brightness: e.brightness,
            foreground: colors[e.pair.foreground],
            background: [for (final role in [e.pair.background, ...e.pair.over]) colors[role]],
            ratio: e.ratio,
            reason: e.reason,
          ),
    ],
    entry: ${verifyEntryClosure(prefix, entry)},
  );
}
''';
}

/// `logicalSize`, et `platformSizes` quand Android a sa propre taille.
String _canvasArguments(VerifyCanvas? canvas) => switch (canvas) {
  null => '',
  UniformCanvas(:final size) =>
    '    logicalSize: const Size(${size.width}, ${size.height}),\n',
  PlatformCanvas(:final ios, :final android) =>
    '    logicalSize: const Size(${ios.width}, ${ios.height}),\n'
        '    platformSizes: const {TargetPlatform.android: '
        'Size(${android.width}, ${android.height})},\n',
};

/// La fonction d'entrée passée à `fliinVerify` : [entry] pompée sous
/// `{prefix}Scope`. Les goldens de référence du registre sont rendus par la
/// même (`packages/fliin/tool/gen_verify_entries.dart`), pour qu'un `fliin
/// verify` aux jetons par défaut leur soit identique au pixel près.
String verifyEntryClosure(String prefix, String entry) =>
    '''(context, variant) => ${prefix}Scope(
      brightness: variant.brightness,
      platform: variant.platform,
      child: Builder(builder: (context) => $entry),
    )''';
