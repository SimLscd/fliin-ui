import 'package:fliin_schema/fliin_schema.dart';

/// The text of `tokens.g.dart` for [tokens], classes prefixed with [prefix]
/// (`Fl` in the registry). Unformatted: the caller goes through the embedded
/// `dart_style`, so that the file installed by `init` and the one
/// `fliin tokens` regenerates are identical. Each argument is on its own line
/// with a trailing comma, so that the layout does not depend on the length of
/// the prefix.
String tokensDart(FliinTokens tokens, {required String prefix}) =>
    _Writer(tokens, prefix).write();

/// One `final ${prefix}Tokens <name>` variable per entry of [named], on the
/// `tokens.g.dart` classes imported from [tokensImport]: test themes that go
/// through the same profile and the same generator as the registry.
/// Unformatted, like [tokensDart].
String tokensValuesDart(
  Map<String, FliinTokens> named, {
  required String prefix,
  required String tokensImport,
}) {
  final out = StringBuffer()
    ..writeln(
      '// Generated by packages/fliin/tool/gen_tokens.dart from the neighboring '
      '*.tokens.json. '
      'Do not edit: change the JSON and rerun.',
    )
    ..writeln("import 'package:flutter/widgets.dart';")
    ..writeln("import '$tokensImport';");
  for (final MapEntry(key: name, value: tokens) in named.entries) {
    final writer = _Writer(tokens, prefix).._value();
    out
      ..write('\nfinal ${prefix}Tokens $name = ')
      ..write(writer.out)
      ..writeln(';');
  }
  return out.toString();
}

final class _Writer {
  _Writer(this.t, this.p);

  final FliinTokens t;
  final String p;
  final out = StringBuffer();

  String write() {
    out.writeln(
      '// Generated by fliin tokens from fliin.tokens.json. Do not edit: '
      'change the JSON and rerun.',
    );
    if (t.notice case final notice?) {
      for (final line in notice.split('\n')) {
        out.writeln('// $line');
      }
    }
    out.writeln("import 'package:flutter/widgets.dart';");
    _colors();
    _shape();
    _shadows();
    _simple(
      '${p}SpaceTokens',
      'The spacings of `space`, in logical pixels.',
      'space',
      t.space.keys,
    );
    _simple(
      '${p}SizeTokens',
      'The sizes of `size`: control heights and paddings per density,\n'
          'touch targets, strokes and control dimensions.',
      'size',
      t.size.keys,
    );
    _motion();
    _typography();
    _defaults();
    return out.toString();
  }

  void _colors() {
    out.writeln();
    _doc(
      'The color roles of `color.light` and `color.dark`, in the order '
      'of fliin.tokens.json;\n`colors[role]` reads a role from [${p}ColorTokens].',
    );
    out.writeln('enum ${p}ColorRole {');
    for (final role in t.roles) {
      _doc('Role `$role`: `color.light.$role` and `color.dark.$role`.', '  ');
      out.writeln('  $role,');
    }
    out.writeln('}');
    out.writeln();
    _doc(
      'The WCAG contrast threshold a [${p}ContrastPair] must reach.',
    );
    out.writeln('enum ${p}ContrastKind {');
    _doc('Text: at least 4.5:1.', '  ');
    out.writeln('  text,');
    _doc('User interface component (stroke, ring, track): at least 3:1.', '  ');
    out.writeln('  ui,');
    out.writeln('}');
    out.writeln();
    _doc(
      'A [foreground] text or component placed on [background], itself\n'
      'placed on the [over] layers (from top to bottom, the last one opaque),\n'
      'whose contrast must reach the threshold of [kind].',
    );
    out.writeln('typedef ${p}ContrastPair = ({');
    out.writeln('  ${p}ColorRole foreground,');
    out.writeln('  ${p}ColorRole background,');
    out.writeln('  List<${p}ColorRole> over,');
    out.writeln('  ${p}ContrastKind kind,');
    out.writeln('});');
    out.writeln();
    _doc(
      'A [pair] the theme declares below its threshold in [brightness], with its\n'
      '[ratio] measured rounded down to the hundredth and the [reason] for the choice\n'
      '(`\$extensions.${FliinTokens.contrastExceptionsExtension}` of `color`).',
    );
    out.writeln('typedef ${p}ContrastException = ({');
    out.writeln('  ${p}ContrastPair pair,');
    out.writeln('  Brightness brightness,');
    out.writeln('  double ratio,');
    out.writeln('  String reason,');
    out.writeln('});');
    _classHead(
      '${p}ColorTokens',
      'The colors of one mode, light or dark, one per [${p}ColorRole].',
      [
        for (final role in t.roles)
          ('Color', role, 'Role `$role`, token `color.<mode>.$role`.'),
      ],
    );
    out.writeln();
    _doc('The color of [role] in this mode.', '  ');
    out.writeln('  Color operator [](${p}ColorRole role) => switch (role) {');
    for (final role in t.roles) {
      out.writeln('    ${p}ColorRole.$role => $role,');
    }
    out.writeln('  };');
    out.writeln();
    _doc(
      'The role pairs whose contrast is required in both modes,\n'
          'read from `\$extensions.${FliinTokens.contrastExtension}` of `color`.',
      '  ',
    );
    out.writeln('  static const List<${p}ContrastPair> contrastPairs = [');
    for (final pair in t.contrastPairs) {
      _pair(pair, '    ');
      out.writeln(',');
    }
    out.writeln('  ];');
    out.writeln('}');
  }

  void _pair(ContrastPair pair, String indent) {
    out.writeln('$indent(');
    out.writeln('$indent  foreground: ${p}ColorRole.${pair.foreground},');
    out.writeln('$indent  background: ${p}ColorRole.${pair.background},');
    out.writeln(
      '$indent  over: [${[for (final role in pair.over) '${p}ColorRole.$role,'].join(' ')}],',
    );
    out.writeln('$indent  kind: ${p}ContrastKind.${pair.kind.name},');
    out.write('$indent)');
  }

  void _shape() {
    out.writeln();
    _doc('The shape of buttons, token `shape.button`.');
    out.writeln('enum ${p}ButtonShape {');
    for (final shape in ButtonShape.values) {
      _doc(switch (shape) {
        ButtonShape.square => 'Square corners.',
        ButtonShape.rounded => 'Corners with the `radiusControl` radius.',
        ButtonShape.pill => 'Semicircular ends.',
      }, '  ');
      out.writeln('  ${shape.name},');
    }
    out.writeln('}');
    _classHead(
      '${p}ShapeTokens',
      'The radii of `shape.radius` and the shape of buttons.',
      [
        for (final name in t.radius.keys)
          (
            'double',
            _radiusField(name),
            'Radius in logical pixels, token `shape.radius.$name`.',
          ),
        (
          '${p}ButtonShape',
          'button',
          'The shape of buttons, token `shape.button`.',
        ),
      ],
    );
    out.writeln();
    _doc('The border radius of buttons, derived from [button].', '  ');
    out.writeln('  BorderRadius get buttonRadius => switch (button) {');
    out.writeln('    ${p}ButtonShape.square => BorderRadius.zero,');
    out.writeln(
      '    ${p}ButtonShape.rounded => BorderRadius.circular(radiusControl),',
    );
    out.writeln('    ${p}ButtonShape.pill => BorderRadius.circular(9999),');
    out.writeln('  };');
    out.writeln('}');
  }

  void _shadows() {
    _classHead(
      '${p}ShadowLayer',
      'A shadow layer, DTCG type `shadow`: like a CSS `box-shadow`,\n'
          'shifted by [offset], blurred by [blur] (the CSS radius, twice the standard\n'
          'deviation), spread by [spread], and painted inside the shape when [inset].',
      const [
        ('Color', 'color', 'The shadow color.'),
        ('Offset', 'offset', 'The offset, in logical pixels.'),
        ('double', 'blur', 'The CSS blur radius, in logical pixels.'),
        ('double', 'spread', 'The spread, in logical pixels.'),
        ('bool', 'inset', 'True for an inner shadow.'),
      ],
    );
    out.writeln('}');
    final names = t.shadows.values.first.keys;
    _classHead(
      '${p}Shadows',
      'The shadows of one mode, light or dark, `shadow.<mode>`.',
      [
        for (final name in names)
          (
            'List<${p}ShadowLayer>',
            name,
            'Shadow `shadow.<mode>.$name`, its layers from top to bottom.',
          ),
      ],
    );
    out.writeln('}');
    _classHead(
      '${p}ShadowTokens',
      'The shadows of both modes, `shadow`.',
      [
        for (final appearance in FliinTokens.appearances)
          (
            '${p}Shadows',
            appearance,
            'The ${appearance == 'light' ? 'light' : 'dark'} mode shadows, `shadow.$appearance`.',
          ),
      ],
    );
    out.writeln('}');
  }

  void _simple(String name, String doc, String group, Iterable<String> fields) {
    _classHead(name, doc, [
      for (final field in fields) ('double', field, 'Token `$group.$field`.'),
    ]);
    out.writeln('}');
  }

  void _motion() {
    _classHead(
      '${p}MotionTokens',
      'The springs, curves and durations of `motion`.',
      [
        for (final name in t.springs.keys)
          ('SpringDescription', name, 'Spring `motion.spring.$name`.'),
        for (final name in t.curves.keys)
          ('Curve', name, 'Cubic Bézier curve `motion.curve.$name`.'),
        for (final name in t.durations.keys)
          ('Duration', name, 'Duration `motion.duration.$name`.'),
        (
          'double',
          'pressedScale',
          'Scale factor of a pressed element, token `motion.pressedScale`.',
        ),
      ],
    );
    out.writeln('}');
  }

  void _typography() {
    _classHead(
      '${p}TypeStyle',
      'A text style of a type scale.',
      const [
        ('double', 'size', 'Font size in logical pixels.'),
        ('double', 'lineHeight', 'Line height in logical pixels.'),
        ('FontWeight', 'weight', 'Font weight.'),
        ('double', 'tracking', 'Tracking in logical pixels, the text\'s `letterSpacing`.'),
      ],
    );
    out.writeln('}');
    _classHead(
      '${p}TypeScale',
      'The type scale of a platform, `typography.scale.<platform>`.',
      [
        for (final role in t.typography.values.first.keys)
          (
            '${p}TypeStyle',
            role,
            'Type role `$role`, token `typography.scale.<platform>.$role`.',
          ),
        (
          'String?',
          'fontFamily',
          'The named font of `typography.family.<platform>`, or null for the '
              'system font.',
        ),
        (
          'String',
          'monospaceFamily',
          'The monospace font for code, `typography.monospace.<platform>`.',
        ),
      ],
      optional: const [
        (
          'String?',
          'headingFamily',
          'The named heading font, `typography.headingFamily.<platform>`, '
              'or null for the text font.',
          null,
        ),
      ],
    );
    out.writeln('}');
    _classHead(
      '${p}FontWeights',
      'The named weights of `typography.weight`.',
      [
        for (final name in t.fontWeights.keys)
          ('FontWeight', name, 'Weight `typography.weight.$name`.'),
      ],
    );
    out.writeln('}');
    _classHead(
      '${p}Typography',
      'The type scales, one per platform, and the weights.',
      [
        for (final platform in t.typography.keys)
          (
            '${p}TypeScale',
            platform,
            'The `$platform` scale, token `typography.scale.$platform`.',
          ),
        (
          '${p}FontWeights',
          'weight',
          'The named weights, `typography.weight`.',
        ),
      ],
    );
    out.writeln('}');
  }

  void _defaults() {
    _classHead(
      '${p}Tokens',
      'All the tokens of a theme, grouped by family.',
      [
        (
          '${p}ColorTokens',
          'light',
          'The light mode colors, `color.light`.',
        ),
        (
          '${p}ColorTokens',
          'dark',
          'The dark mode colors, `color.dark`.',
        ),
        (
          '${p}ShapeTokens',
          'shape',
          'The radii and the shape of buttons, `shape`.',
        ),
        (
          '${p}ShadowTokens',
          'shadow',
          'The shadows of both modes, `shadow`.',
        ),
        ('${p}SpaceTokens', 'space', 'The spacings, `space`.'),
        ('${p}SizeTokens', 'size', 'The sizes, `size`.'),
        (
          '${p}MotionTokens',
          'motion',
          'The springs, curves and durations, `motion`.',
        ),
        (
          '${p}Typography',
          'typography',
          'The type scales, `typography`.',
        ),
      ],
      optional: [
        (
          'List<${p}ContrastException>',
          'contrastExceptions',
          'The pairs this theme declares below their threshold, warnings of\n'
              '`fliin verify` and `fliin theme`; empty by default.',
          'const []',
        ),
      ],
    );
    out.writeln();
    _doc('The values of fliin.tokens.json at generation time.', '  ');
    out.write('  static final ${p}Tokens defaults = ');
    _value();
    out.writeln(';');
    out.writeln('}');
  }

  void _value() {
    out.writeln('${p}Tokens(');
    _colorDefaults('light', t.light);
    _colorDefaults('dark', t.dark);
    out.writeln('    shape: const ${p}ShapeTokens(');
    for (final MapEntry(key: name, value: px) in t.radius.entries) {
      out.writeln('      ${_radiusField(name)}: ${_num(px)},');
    }
    out.writeln('      button: ${p}ButtonShape.${t.button.name},');
    out.writeln('    ),');
    out.writeln('    shadow: const ${p}ShadowTokens(');
    for (final MapEntry(key: appearance, value: shadows) in t.shadows.entries) {
      out.writeln('      $appearance: ${p}Shadows(');
      for (final MapEntry(key: name, value: layers) in shadows.entries) {
        out.writeln('        $name: [');
        for (final layer in layers) {
          out.writeln('          ${p}ShadowLayer(');
          out.writeln('            color: Color(${_hex(layer.color)}),');
          out.writeln(
            '            offset: Offset(${_num(layer.offsetX)}, ${_num(layer.offsetY)}),',
          );
          out.writeln('            blur: ${_num(layer.blur)},');
          out.writeln('            spread: ${_num(layer.spread)},');
          out.writeln('            inset: ${layer.inset},');
          out.writeln('          ),');
        }
        out.writeln('        ],');
      }
      out.writeln('      ),');
    }
    out.writeln('    ),');
    _numberDefaults('space', '${p}SpaceTokens', t.space);
    _numberDefaults('size', '${p}SizeTokens', t.size);
    out.writeln('    motion: ${p}MotionTokens(');
    for (final MapEntry(key: name, value: spring) in t.springs.entries) {
      out.writeln('      $name: SpringDescription.withDampingRatio(');
      out.writeln('        mass: ${_num(spring.mass)},');
      out.writeln('        stiffness: ${_num(spring.stiffness)},');
      out.writeln('        ratio: ${_num(spring.dampingRatio)},');
      out.writeln('      ),');
    }
    for (final MapEntry(key: name, value: curve) in t.curves.entries) {
      out.writeln(
        '      $name: const Cubic(${_num(curve.x1)}, ${_num(curve.y1)}, '
        '${_num(curve.x2)}, ${_num(curve.y2)}),',
      );
    }
    for (final MapEntry(key: name, value: duration) in t.durations.entries) {
      out.writeln('      $name: const ${_duration(duration)},');
    }
    out.writeln('      pressedScale: ${_num(t.pressedScale)},');
    out.writeln('    ),');
    out.writeln('    typography: const ${p}Typography(');
    for (final MapEntry(key: platform, value: scale) in t.typography.entries) {
      out.writeln('      $platform: ${p}TypeScale(');
      for (final MapEntry(key: role, value: style) in scale.entries) {
        out.writeln('        $role: ${p}TypeStyle(');
        out.writeln('          size: ${_num(style.size)},');
        out.writeln('          lineHeight: ${_num(style.lineHeight)},');
        out.writeln('          weight: FontWeight.w${style.weight.round()},');
        out.writeln('          tracking: ${_num(style.tracking)},');
        out.writeln('        ),');
      }
      out.writeln('        fontFamily: ${_string(t.fontFamily[platform])},');
      if (t.headingFamily[platform] case final family?) {
        out.writeln('        headingFamily: ${_string(family)},');
      }
      out.writeln(
        '        monospaceFamily: ${_string(t.monospaceFamily[platform])},',
      );
      out.writeln('      ),');
    }
    out.writeln('      weight: ${p}FontWeights(');
    for (final MapEntry(key: name, value: weight) in t.fontWeights.entries) {
      out.writeln('        $name: FontWeight.w${weight.round()},');
    }
    out.writeln('      ),');
    out.writeln('    ),');
    if (t.contrastExceptions.isNotEmpty) {
      out.writeln('    contrastExceptions: const [');
      for (final e in t.contrastExceptions) {
        out.writeln('      (');
        out.write('        pair: ');
        _pair(e.pair, '        ');
        out.writeln(',');
        out.writeln('        brightness: Brightness.${e.appearance},');
        out.writeln('        ratio: ${_num(e.ratio)},');
        out.writeln('        reason: ${_string(e.reason)},');
        out.writeln('      ),');
      }
      out.writeln('    ],');
    }
    out.write('  )');
  }

  void _colorDefaults(String field, Map<String, int> colors) {
    out.writeln('    $field: const ${p}ColorTokens(');
    for (final MapEntry(key: role, value: argb) in colors.entries) {
      out.writeln('      $role: Color(${_hex(argb)}),');
    }
    out.writeln('    ),');
  }

  void _numberDefaults(String field, String type, Map<String, double> values) {
    out.writeln('    $field: const $type(');
    for (final MapEntry(key: name, value: number) in values.entries) {
      out.writeln('      $name: ${_num(number)},');
    }
    out.writeln('    ),');
  }

  /// `final class`, a const constructor with required named parameters, and
  /// fields, each with its doc (`public_member_api_docs`, DESIGN.md §6.5).
  void _classHead(
    String name,
    String doc,
    List<(String type, String field, String doc)> fields, {
    List<(String type, String field, String doc, String? fallback)> optional =
        const [],
  }) {
    out.writeln();
    _doc(doc);
    out.writeln('final class $name {');
    _doc(
      'One value per field; [${p}Tokens.defaults] holds the project\'s.',
      '  ',
    );
    out.writeln('  const $name({');
    for (final (_, field, _) in fields) {
      out.writeln('    required this.$field,');
    }
    for (final (_, field, _, fallback) in optional) {
      out.writeln('    this.$field${fallback == null ? '' : ' = $fallback'},');
    }
    out.writeln('  });');
    for (final (type, field, doc) in [
      ...fields,
      for (final (type, field, doc, _) in optional) (type, field, doc),
    ]) {
      out.writeln();
      _doc(doc, '  ');
      out.writeln('  final $type $field;');
    }
  }

  void _doc(String text, [String indent = '']) {
    for (final line in text.split('\n')) {
      out.writeln('$indent/// $line');
    }
  }

  /// The profile has rejected control characters; what remains to escape are
  /// those a single-quoted Dart string interprets.
  static String _string(String? value) {
    if (value == null) return 'null';
    final escaped = value
        .replaceAll(r'\', r'\\')
        .replaceAll("'", r"\'")
        .replaceAll(r'$', r'\$');
    return "'$escaped'";
  }

  static String _radiusField(String name) =>
      'radius${name[0].toUpperCase()}${name.substring(1)}';

  static String _hex(int argb) =>
      '0x${argb.toRadixString(16).toUpperCase().padLeft(8, '0')}';

  /// Beyond 2^53, `round()` no longer returns the value: the double form
  /// keeps it.
  static String _num(double value) =>
      value == value.roundToDouble() && value.abs() <= 9007199254740992
      ? '${value.round()}'
      : '$value';

  static String _duration(DurationValue duration) {
    final ms = duration.milliseconds;
    return ms == ms.roundToDouble()
        ? 'Duration(milliseconds: ${ms.round()})'
        : 'Duration(microseconds: ${(ms * 1000).round()})';
  }
}
